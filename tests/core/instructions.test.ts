import { describe, expect, it } from "vitest";
import {
  findConditionalTags,
  GENERATED_HEADER,
  hasGeneratedHeader,
} from "../../src/core/instructions.js";

const BOM = "﻿";

describe("GENERATED_HEADER", () => {
  it("is the fixed generated-file marker", () => {
    expect(GENERATED_HEADER).toBe("<!-- GENERATED BY YOKE — DO NOT EDIT DIRECTLY -->");
  });
});

describe("hasGeneratedHeader", () => {
  it("is true when the first line is the header", () => {
    expect(hasGeneratedHeader(`${GENERATED_HEADER}\n# Rules\n`)).toBe(true);
  });

  it("ignores a leading BOM and trailing whitespace on the first line", () => {
    expect(hasGeneratedHeader(`${BOM}${GENERATED_HEADER}\nbody\n`)).toBe(true);
    expect(hasGeneratedHeader(`${GENERATED_HEADER}   \r\nbody\r\n`)).toBe(true);
  });

  it("accepts a header with no trailing newline", () => {
    expect(hasGeneratedHeader(GENERATED_HEADER)).toBe(true);
  });

  it("is false when the header is not on the first line", () => {
    expect(hasGeneratedHeader(`# Title\n${GENERATED_HEADER}\n`)).toBe(false);
  });

  it("is false for an empty or unrelated file", () => {
    expect(hasGeneratedHeader("")).toBe(false);
    expect(hasGeneratedHeader("<!-- GENERATED BY SOMEONE ELSE -->\n")).toBe(false);
  });
});

describe("findConditionalTags", () => {
  it("returns an empty array when there are no legacy tags", () => {
    expect(findConditionalTags("# Rules\n\nUse tabs.\n")).toEqual([]);
    expect(findConditionalTags("")).toEqual([]);
  });

  it("reports opening and closing claude-only and agy-only tags with 1-based line numbers", () => {
    const text = [
      "shared",
      "<!-- yoke:claude-only -->",
      "claude text",
      "<!-- /yoke:claude-only -->",
      "",
      "<!-- yoke:agy-only -->",
      "agy text",
      "<!-- /yoke:agy-only -->",
      "",
    ].join("\n");
    expect(findConditionalTags(text)).toEqual([2, 4, 6, 8]);
  });

  it("finds indented tags and tags with irregular inner spacing", () => {
    const text = "x\n    <!--yoke:claude-only-->\n  <!--   /yoke:agy-only  -->\n";
    expect(findConditionalTags(text)).toEqual([2, 3]);
  });

  it("handles CRLF line endings and a leading BOM", () => {
    const text = `${BOM}one\r\n<!-- yoke:claude-only -->\r\ntwo\r\n<!-- /yoke:claude-only -->\r\n`;
    expect(findConditionalTags(text)).toEqual([2, 4]);
  });

  it("does not report tags for other harness names or unrelated yoke comments", () => {
    const text = "<!-- yoke:gemini-only -->\n<!-- yoke:note -->\n<!-- yoke:claude -->\n";
    expect(findConditionalTags(text)).toEqual([]);
  });

  it("reports tags inside fenced code, since the scan does not parse fences", () => {
    const text = "```md\n<!-- yoke:agy-only -->\n```\n";
    expect(findConditionalTags(text)).toEqual([2]);
  });
});

/**
 * src/commands/init-convert.ts — turns an import selection into a secret-free yoke.yaml draft and the write intents
 * that would create it. Pure: no I/O, no clock, no process access. Nothing is written here.
 */
import { isAbsolute, join, relative, sep } from "node:path";
import { stringify } from "yaml";
import { hashMcp } from "../core/drift.js";
import {
  type McpServerDefinition,
  type Mode,
  type YokeConfig,
  YokeConfigSchema,
} from "../core/schema.js";
import { findLiteralSecrets, redactSecrets, type SecretFinding } from "../core/secrets.js";
import {
  type HarnessImport,
  type ImportSelection,
  InitError,
  type ProjectWriteIntent,
} from "./init-types.js";

/** `local`: full original definitions go to yoke.local.yaml. `ref`: references only. */
export type SecretPolicy = "local" | "ref";

export interface InitDraft {
  readonly project: YokeConfig;
  readonly local: YokeConfig | undefined;
  /** Native user-tier servers not already in project or local, for the user-scope file. */
  readonly user:
    | {
        readonly mcps: Readonly<Record<string, McpServerDefinition>>;
        readonly harnesses: readonly string[];
      }
    | undefined;
  readonly agents: { readonly content: string; readonly from: string } | undefined;
  readonly envVars: readonly SecretFinding[];
  readonly notes: readonly string[];
}

const YAML_HEADER = "# Generated by yoke init; edit freely.\n";
const ALWAYS_IGNORED: readonly string[] = [".yoke/", "yoke.local.yaml"];
const NEVER_IGNORED: ReadonlySet<string> = new Set(["AGENTS.md", "yoke.yaml"]);

interface Claim {
  readonly harness: string;
  readonly def: McpServerDefinition;
}

/** Merges one tier across harnesses. Identical definitions collapse; different ones fail. */
function mergeTier(
  tier: "project" | "local" | "user",
  harnesses: readonly HarnessImport[],
): Record<string, McpServerDefinition> {
  const claimed = new Map<string, Claim>();
  for (const harness of harnesses) {
    const servers =
      tier === "project" ? harness.project : tier === "local" ? harness.local : harness.user;
    for (const [name, def] of Object.entries(servers)) {
      const prior = claimed.get(name);
      if (prior === undefined) {
        claimed.set(name, { harness: harness.harness, def });
      } else if (hashMcp(prior.def) !== hashMcp(def)) {
        throw new InitError(
          `MCP server "${name}" differs between harnesses "${prior.harness}" and "${harness.harness}" (${tier} scope); keep one of them or use a different name for one`,
        );
      }
    }
  }
  return Object.fromEntries([...claimed].map(([name, claim]) => [name, claim.def]));
}

/**
 * Builds the drafts for yoke.yaml, yoke.local.yaml, and the user-scope draft.
 * Literal secrets in the project tier become `${VAR}` references; `local` keeps their full originals in the local
 * draft. User-tier servers keep literal values under `local` and become references under `ref`.
 */
export function buildInitDraft(input: {
  readonly selection: ImportSelection;
  readonly installed: readonly string[];
  readonly secrets: SecretPolicy;
}): InitDraft {
  const { selection, installed, secrets } = input;
  const projectNative = mergeTier("project", selection.harnesses);
  const localMap: Record<string, McpServerDefinition> = mergeTier("local", selection.harnesses);
  const projectOrLocalNames = new Set([...Object.keys(projectNative), ...Object.keys(localMap)]);
  const redacted = redactSecrets(projectNative);

  if (secrets === "local") {
    for (const [name, def] of Object.entries(redacted.original)) {
      const existing = localMap[name];
      if (existing !== undefined && hashMcp(existing) !== hashMcp(def)) {
        throw new InitError(
          `MCP server "${name}" has literal secrets in project scope and a different local-scope definition; resolve it by hand`,
        );
      }
      localMap[name] = def;
    }
  }

  const notes: string[] = [];
  const user = buildUserDraft({
    selection,
    projectOrLocalNames,
    secrets,
    takenVarNames: new Set(redacted.findings.map((f) => f.varName)),
    notes,
  });

  const harnessNames = [
    ...new Set([...installed, ...selection.harnesses.map((h) => h.harness)]),
  ].sort();
  const project = YokeConfigSchema.parse({
    version: 1,
    harnesses: harnessNames,
    ...(Object.keys(redacted.safe).length > 0 ? { mcps: redacted.safe } : {}),
  });
  if (findLiteralSecrets(redacted.safe).length > 0) {
    throw new Error("internal: literal secret");
  }

  const local =
    Object.keys(localMap).length > 0
      ? YokeConfigSchema.parse({ version: 1, mcps: localMap })
      : undefined;

  const instructions = selection.instructions;
  const agents =
    instructions === undefined
      ? undefined
      : { content: instructions.content, from: instructions.path };

  const envVars = [...redacted.findings, ...(user?.findings ?? [])];
  if (secrets === "local") {
    if (redacted.findings.length > 0) {
      notes.push(
        `${redacted.findings.length} literal secret value(s) replaced by \${VAR} references; full definitions kept in yoke.local.yaml`,
      );
    }
  } else if (envVars.length > 0) {
    const names = [...new Set(envVars.map((f) => f.varName))].join(", ");
    notes.push(`export these variables before running sync: ${names}`);
  }

  return {
    project,
    local,
    user: user === undefined ? undefined : { mcps: user.mcps, harnesses: user.harnesses },
    agents,
    envVars,
    notes,
  };
}

/**
 * The user-scope draft. Names already in the project or local draft are left out, with a note. Under
 * `ref`, literal secrets become references; the findings are returned so the caller can list them.
 */
function buildUserDraft(input: {
  readonly selection: ImportSelection;
  readonly projectOrLocalNames: ReadonlySet<string>;
  readonly secrets: SecretPolicy;
  readonly takenVarNames: ReadonlySet<string>;
  readonly notes: string[];
}):
  | {
      readonly mcps: Record<string, McpServerDefinition>;
      readonly harnesses: string[];
      readonly findings: SecretFinding[];
    }
  | undefined {
  const { selection, projectOrLocalNames, secrets, takenVarNames, notes } = input;
  const merged = mergeTier("user", selection.harnesses);
  const mcps: Record<string, McpServerDefinition> = {};
  for (const name of Object.keys(merged).sort()) {
    const def = merged[name];
    if (def === undefined) {
      continue;
    }
    if (projectOrLocalNames.has(name)) {
      notes.push(`user server "${name}" also defined in project/local; not added to the user file`);
      continue;
    }
    mcps[name] = def;
  }
  if (Object.keys(mcps).length === 0) {
    return undefined;
  }
  const harnesses = selection.harnesses
    .filter((h) => Object.keys(h.user).some((name) => Object.hasOwn(mcps, name)))
    .map((h) => h.harness);
  const uniqueHarnesses = [...new Set(harnesses)].sort();

  if (secrets === "local") {
    return { mcps, harnesses: uniqueHarnesses, findings: [] };
  }
  const redacted = redactSecrets(mcps, takenVarNames);
  return {
    mcps: { ...redacted.safe },
    harnesses: uniqueHarnesses,
    findings: [...redacted.findings],
  };
}

/** Serializes a config as yoke.yaml text. `${VAR}` references are written verbatim. */
export function renderYokeYaml(config: YokeConfig): string {
  return `${YAML_HEADER}${stringify(config)}`;
}

/**
 * Lines for `.gitignore`. In compiled mode, generated project paths inside the repo are added as
 * `/`-anchored entries; `AGENTS.md` and `yoke.yaml` are never ignored. Sorted and unique.
 */
export function gitignoreLines(input: {
  readonly mode: Mode;
  readonly repoPath: string;
  readonly generatedPaths: readonly string[];
}): readonly string[] {
  const lines = new Set<string>(ALWAYS_IGNORED);
  if (input.mode === "compiled") {
    for (const path of input.generatedPaths) {
      if (!isAbsolute(path)) {
        continue;
      }
      const rel = relative(input.repoPath, path);
      if (rel === "" || rel === ".." || rel.startsWith(`..${sep}`) || isAbsolute(rel)) {
        continue;
      }
      const posix = rel.split(sep).join("/");
      if (NEVER_IGNORED.has(posix)) {
        continue;
      }
      lines.add(`/${posix}`);
    }
  }
  return [...lines].sort();
}

/**
 * Write intents for the draft. Only `<repo>/yoke.yaml`, `<repo>/yoke.local.yaml`, `<repo>/AGENTS.md` and
 * `<repo>/.gitignore` can appear. `gitignore: undefined` means `--no-gitignore`.
 */
export function draftToIntents(
  draft: InitDraft,
  input: {
    readonly repoPath: string;
    readonly force: boolean;
    readonly gitignore: readonly string[] | undefined;
  },
): readonly ProjectWriteIntent[] {
  const ifExists: "fail" | "overwrite-with-backup" = input.force ? "overwrite-with-backup" : "fail";
  const intents: ProjectWriteIntent[] = [
    {
      kind: "text",
      scope: "project",
      path: join(input.repoPath, "yoke.yaml"),
      content: renderYokeYaml(draft.project),
      ifExists,
    },
  ];
  if (draft.local !== undefined) {
    intents.push({
      kind: "text",
      scope: "local",
      path: join(input.repoPath, "yoke.local.yaml"),
      content: renderYokeYaml(draft.local),
      ifExists,
    });
  }
  if (draft.agents !== undefined) {
    intents.push({
      kind: "text",
      scope: "project",
      path: join(input.repoPath, "AGENTS.md"),
      content: draft.agents.content,
      ifExists,
    });
  }
  if (input.gitignore !== undefined && input.gitignore.length > 0) {
    intents.push({
      kind: "ensure-lines",
      scope: "project",
      path: join(input.repoPath, ".gitignore"),
      lines: input.gitignore,
    });
  }
  return intents;
}

/**
 * src/core/instructions.ts — helpers for the native instruction layout (decision-0008).
 *
 * AGENTS.md is the only shared instruction file. yoke never generates project instruction text, so this module only
 * recognises files yoke used to generate (GENERATED_HEADER) and reports leftover conditional tags.
 *
 * Pure: no file I/O, no clock, no environment access. Callers supply the text.
 */

export const GENERATED_HEADER = "<!-- GENERATED BY YOKE — DO NOT EDIT DIRECTLY -->";

const BOM = "﻿";

/** Matches an opening or closing `yoke:<word>-only` tag anywhere on a line. Fences are not parsed. */
const LEGACY_TAG = /<!--\s*\/?yoke:[a-z]+-only\s*-->/;

/** True when the first line (after an optional BOM and trailing whitespace) is the GENERATED header. */
export function hasGeneratedHeader(text: string): boolean {
  const body = text.startsWith(BOM) ? text.slice(BOM.length) : text;
  const newline = body.indexOf("\n");
  const firstLine = newline === -1 ? body : body.slice(0, newline);
  return firstLine.trimEnd() === GENERATED_HEADER;
}

/**
 * 1-based line numbers that contain a leftover `yoke:<word>-only` tag (opening or closing), in
 * ascending order. An empty array means the text has no legacy tags.
 */
export function findConditionalTags(text: string): number[] {
  const body = text.startsWith(BOM) ? text.slice(BOM.length) : text;
  const lines: number[] = [];
  body.split(/\r?\n/).forEach((line, index) => {
    if (LEGACY_TAG.test(line)) {
      lines.push(index + 1);
    }
  });
  return lines;
}

/**
 * src/core/compiler.ts — conditional instruction block parser and compiler (SPEC §4.2).
 *
 * Pure: no file I/O, no clock, no environment access. Callers supply the text.
 */

export const GENERATED_HEADER = "<!-- GENERATED BY YOKE — DO NOT EDIT DIRECTLY -->";

export type CompileErrorCode =
  | "unclosed"
  | "nested"
  | "unmatched-close"
  | "mismatched-close"
  | "malformed-tag"
  | "unknown-target";

export class InstructionCompileError extends Error {
  readonly code: CompileErrorCode;
  /** 1-based line number in the input text. */
  readonly line: number;

  constructor(message: string, code: CompileErrorCode, line: number) {
    super(`${message} (line ${line})`);
    this.name = "InstructionCompileError";
    this.code = code;
    this.line = line;
  }
}

export interface ConditionalBlock {
  readonly target: string;
  readonly openLine: number;
  readonly closeLine: number;
}

export interface ParseOptions {
  /** When given, any block naming a target outside this list is an error. */
  readonly validTargets?: readonly string[];
}

export interface ParsedInstructions {
  readonly blocks: readonly ConditionalBlock[];
  /** Unique target names, in first-seen order. */
  readonly targets: readonly string[];
}

// Tags and fences follow CommonMark: 4 or more leading spaces is indented code, not markup.
// Tabs are not accepted as indentation here, so a tab-led tag line is ordinary text.
const OPEN_TAG = /^ {0,3}<!--\s*yoke:([a-z][a-z0-9-]{0,31})-only\s*-->\s*$/;
const CLOSE_TAG = /^ {0,3}<!--\s*\/yoke:([a-z][a-z0-9-]{0,31})-only\s*-->\s*$/;
const TAG_LIKE = /^ {0,3}<!--\s*\/?yoke:/;
/** Fence run; applied to the line with its leading spaces removed. */
const FENCE_RUN = /^(`{3,}|~{3,})(.*)$/;
const FENCE_CLOSE_RUN = /^(`{3,}|~{3,})\s*$/;
/** List item marker with 1 to 4 spaces before its content. */
const LIST_ITEM = /^( *)([-*+]|\d{1,9}[.)])( {1,4})\S/;
const BOM = "﻿";

function stripBom(text: string): string {
  return text.startsWith(BOM) ? text.slice(BOM.length) : text;
}

function leadingSpaces(line: string): number {
  return line.length - line.replace(/^ +/, "").length;
}

/**
 * Indentation of a line relative to the innermost open list item's content column.
 * Outside a list (or above it) this is the absolute leading-space count.
 */
function containerIndent(line: string, listColumn: number | undefined): number {
  const lead = leadingSpaces(line);
  return listColumn !== undefined && lead >= listColumn ? lead - listColumn : lead;
}

/** Matches a fence line only when its own indentation (relative to any list item) is 0 to 3. */
function matchFence(
  line: string,
  listColumn: number | undefined,
  run: RegExp,
): RegExpExecArray | null {
  if (containerIndent(line, listColumn) > 3) {
    return null;
  }
  return run.exec(line.slice(leadingSpaces(line)));
}

export function parseConditionalBlocks(text: string, opts?: ParseOptions): ParsedInstructions {
  const lines = stripBom(text).split("\n");
  const blocks: ConditionalBlock[] = [];
  const targets: string[] = [];
  const seen = new Set<string>();
  let current: { readonly target: string; readonly openLine: number } | undefined;
  let fence:
    | { readonly char: string; readonly length: number; readonly listColumn: number | undefined }
    | undefined;
  // Absolute content column of the innermost open list item, if any.
  let listColumn: number | undefined;

  for (let index = 0; index < lines.length; index++) {
    const line = lines[index] ?? "";
    const lineNo = index + 1;

    if (fence !== undefined) {
      const marker = matchFence(line, fence.listColumn, FENCE_CLOSE_RUN)?.[1];
      if (marker !== undefined && marker[0] === fence.char && marker.length >= fence.length) {
        fence = undefined;
      }
      continue;
    }

    // A non-blank line indented less than the item's content column ends the item.
    if (listColumn !== undefined && line.trim() !== "" && leadingSpaces(line) < listColumn) {
      listColumn = undefined;
    }

    const fenceOpen = matchFence(line, listColumn, FENCE_RUN);
    if (fenceOpen !== null) {
      const marker = fenceOpen[1] ?? "";
      const info = fenceOpen[2] ?? "";
      // A backtick fence's info string cannot contain a backtick (CommonMark).
      if (!(marker[0] === "`" && info.includes("`"))) {
        fence = { char: marker[0] ?? "`", length: marker.length, listColumn };
        continue;
      }
    }

    const open = OPEN_TAG.exec(line);
    if (open !== null) {
      const target = open[1] ?? "";
      if (current !== undefined) {
        throw new InstructionCompileError(
          `block "${target}" opened inside block "${current.target}"`,
          "nested",
          lineNo,
        );
      }
      if (opts?.validTargets !== undefined && !opts.validTargets.includes(target)) {
        throw new InstructionCompileError(`unknown target "${target}"`, "unknown-target", lineNo);
      }
      current = { target, openLine: lineNo };
      if (!seen.has(target)) {
        seen.add(target);
        targets.push(target);
      }
      continue;
    }

    const close = CLOSE_TAG.exec(line);
    if (close !== null) {
      const target = close[1] ?? "";
      if (current === undefined) {
        throw new InstructionCompileError(
          `closing tag "${target}" has no open block`,
          "unmatched-close",
          lineNo,
        );
      }
      if (target !== current.target) {
        throw new InstructionCompileError(
          `closing tag "${target}" does not match open block "${current.target}"`,
          "mismatched-close",
          lineNo,
        );
      }
      blocks.push({ target, openLine: current.openLine, closeLine: lineNo });
      current = undefined;
      continue;
    }

    if (TAG_LIKE.test(line)) {
      throw new InstructionCompileError("malformed yoke conditional tag", "malformed-tag", lineNo);
    }

    // Only items within the container (0 to 3 relative spaces) start a list item.
    const item = LIST_ITEM.exec(line);
    if (item !== null && containerIndent(line, listColumn) <= 3) {
      listColumn = (item[1] ?? "").length + (item[2] ?? "").length + (item[3] ?? "").length;
    }
  }

  if (current !== undefined) {
    throw new InstructionCompileError(
      `block "${current.target}" is never closed`,
      "unclosed",
      current.openLine,
    );
  }

  return { blocks, targets };
}

/**
 * Returns the instruction body for one target. Tag lines are dropped; no header is added.
 * A leading BOM is removed. `validTargets` is required: a block naming any other target throws
 * an `unknown-target` InstructionCompileError.
 */
export function compileForTarget(
  text: string,
  target: string,
  validTargets: readonly string[],
): string {
  const { blocks } = parseConditionalBlocks(text, { validTargets });
  const drop = new Set<number>();
  for (const block of blocks) {
    if (block.target === target) {
      drop.add(block.openLine);
      drop.add(block.closeLine);
    } else {
      for (let line = block.openLine; line <= block.closeLine; line++) {
        drop.add(line);
      }
    }
  }
  return stripBom(text)
    .split("\n")
    .filter((_, index) => !drop.has(index + 1))
    .join("\n");
}

export function detectEol(text: string): "\n" | "\r\n" {
  const newline = text.indexOf("\n");
  return newline > 0 && text[newline - 1] === "\r" ? "\r\n" : "\n";
}

export function hasGeneratedHeader(text: string): boolean {
  const body = text.startsWith(BOM) ? text.slice(BOM.length) : text;
  const newline = body.indexOf("\n");
  const firstLine = newline === -1 ? body : body.slice(0, newline);
  return firstLine.trimEnd() === GENERATED_HEADER;
}

/**
 * Compiles source (and an optional local override) for one target. Both texts have a leading BOM
 * stripped, so the generated header is always the first line.
 */
export function compileInstructions(input: {
  readonly source: string;
  readonly local?: string;
  readonly target: string;
  readonly validTargets: readonly string[];
}): string {
  const eol = detectEol(input.source);
  let out =
    GENERATED_HEADER + eol + compileForTarget(input.source, input.target, input.validTargets);

  if (input.local !== undefined) {
    if (!out.endsWith("\n")) {
      out += eol;
    }
    out += eol + compileForTarget(input.local, input.target, input.validTargets);
  }

  if (!out.endsWith("\n")) {
    out += eol;
  }
  return out;
}

// #region C2 strategy

export type CompileReason =
  | "prefer-symlink-off"
  | "conditional-blocks"
  | "local-override"
  | "symlink-unsupported";

export type InstructionStrategy =
  | { readonly kind: "symlink" }
  | { readonly kind: "compile"; readonly reasons: readonly [CompileReason, ...CompileReason[]] };

export interface StrategyInput {
  readonly preferSymlink: boolean;
  /** Canonical instructions text. */
  readonly source: string;
  /** AGENTS.local.md text; undefined means the file is absent (an empty file still counts). */
  readonly local: string | undefined;
  /** Default true; false on platforms where the caller knows links fail. */
  readonly symlinksSupported?: boolean;
  readonly validTargets?: readonly string[];
}

/**
 * Pure decision: symlink only when no compile reason applies (SPEC §4.2).
 * Both texts are always parsed so malformed tags fail early, even when a symlink would be chosen.
 */
export function decideInstructionStrategy(input: StrategyInput): InstructionStrategy {
  const opts: ParseOptions =
    input.validTargets === undefined ? {} : { validTargets: input.validTargets };
  const sourceParsed = parseConditionalBlocks(input.source, opts);
  if (input.local !== undefined) {
    parseConditionalBlocks(input.local, opts);
  }

  const reasons: CompileReason[] = [];
  if (!input.preferSymlink) {
    reasons.push("prefer-symlink-off");
  }
  if (sourceParsed.blocks.length > 0) {
    reasons.push("conditional-blocks");
  }
  if (input.local !== undefined) {
    reasons.push("local-override");
  }
  if (input.symlinksSupported === false) {
    reasons.push("symlink-unsupported");
  }

  const [first, ...rest] = reasons;
  if (first === undefined) {
    return { kind: "symlink" };
  }
  return { kind: "compile", reasons: [first, ...rest] };
}

/**
 * Derives the local override path by inserting ".local" before the last extension of the base name.
 * A leading dot does not count as an extension separator (".hidden.md" -> ".hidden.local.md").
 */
export function localOverridePath(sourcePath: string): string {
  const slash = Math.max(sourcePath.lastIndexOf("/"), sourcePath.lastIndexOf("\\"));
  const dir = sourcePath.slice(0, slash + 1);
  const base = sourcePath.slice(slash + 1);
  const dot = base.lastIndexOf(".");
  if (dot > 0) {
    return `${dir}${base.slice(0, dot)}.local${base.slice(dot)}`;
  }
  return `${dir}${base}.local`;
}

